"""The consolidated RCA Master workbook of a reporting cycle.

Sheets: "Report" (status label, period, version, expected data received), "Coverage" (each expected project /
circle with its accepted records and source files), "Uploads" (each upload for the period with its imported,
updated, skipped and rejected counts), "Summary" (the RCA Summary computed from the same records) and
"RCA Master" (one row per accepted record: the twelve source columns as written, then the record's
current responsibility classification, applicability and provenance, including the upload it came from).
Missing values stay blank, never 0; Other Media records are labelled RCA-not-applicable, apart from records
with missing RCA information.
"""
from __future__ import annotations

import io

from django.utils import timezone
from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from apps.bsnl.classification import get_bucket_classification, load_bucket_mapping, responsibility_label

from .services import MISSING_LABEL, NOT_APPLICABLE_LABEL, RCA_NOT_APPLICABLE

SOURCE_HEADER = ['Date', 'Project', 'Circle', 'Site ID', 'Site Name', 'OA', 'BA', 'O&M Start (Yes/No)', 'Outage Min.',
                 'Final Bucket', 'Bucket - 2', 'RCA']
EXTRA_HEADER = ['RCA applicability', 'Responsibility', 'Circle code', 'Record source', 'Source file', 'Source row', 'Upload ID', 'Record ID']
BOLD = Font(bold=True)
HEAD_FILL = PatternFill('solid', fgColor='E8EEF7')
FINAL_FILL = PatternFill('solid', fgColor='D9F2E3')
PARTIAL_FILL = PatternFill('solid', fgColor='FDE9C8')


def applicability(record) -> str:
    if record.final_bucket_key in RCA_NOT_APPLICABLE:
        return NOT_APPLICABLE_LABEL
    if not (record.final_bucket_key and record.bucket_2_key and record.rca_key):
        return MISSING_LABEL
    return 'RCA recorded'


def _header(ws, row: int, values: list[str]) -> None:
    for col, value in enumerate(values, start=1):
        cell = ws.cell(row=row, column=col, value=value)
        cell.font, cell.fill = BOLD, HEAD_FILL


def _widths(ws, widths: list[int]) -> None:
    for col, width in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(col)].width = width


def _table(ws, start: int, title: str, header: list[str], rows: list[list]) -> int:
    ws.cell(row=start, column=1, value=title).font = Font(bold=True, size=12)
    _header(ws, start + 1, header)
    for offset, values in enumerate(rows, start=start + 2):
        for col, value in enumerate(values, start=1):
            ws.cell(row=offset, column=col, value=value)
    if not rows:
        ws.cell(row=start + 2, column=1, value='No records.')
    return start + 3 + max(len(rows), 1)


def build(*, cycle, records: list, summary: dict, units: list[dict], uploads: list, state: dict, label: str, version: int | None,
          generated_at, generated_by) -> bytes:
    book = Workbook()
    final = version is not None

    # Report ------------------------------------------------------------------------------------
    ws = book.active
    ws.title = 'Report'
    ws['A1'] = 'BSNL 4G Saturation & LWE — Consolidated RCA Master'
    ws['A1'].font = Font(bold=True, size=14)
    ws['A2'] = label
    ws['A2'].font = Font(bold=True, size=13)
    ws['A2'].fill = FINAL_FILL if final else PARTIAL_FILL
    ws.merge_cells('A2:D2')
    outstanding = ', '.join(f'{u["project"]} / {u["circle"]}' for u in state['outstanding']) or 'None'
    start, end = cycle.reporting_date, cycle.end
    info = [
        ('Report name', cycle.name or '—'),
        ('Reporting period', start.strftime('%d %b %Y') if start == end else f'{start:%d %b %Y} to {end:%d %b %Y}'),
        ('Report version', version if final else 'Not a final report (no version)'),
        ('Generated at', timezone.localtime(generated_at).strftime('%d %b %Y %H:%M %Z')),
        ('Generated by', generated_by.get_username() if generated_by else 'Portal (automatic)'),
        ('Period status', state['label']),
        ('Expected projects / circles with accepted data', f'{state["received"]} of {state["required"]}' if state['required']
         else 'No expected scope configured'),
        ('Pending (no accepted records)', outstanding),
        ('Accepted RCA records', len(records)),
        ('Records fingerprint (SHA-256)', state['records_checksum']),
        ('Note', 'Built from the accepted records stored in the portal database. Outage minutes are as reported in the RCA files; '
                 'blank values are not reported (never 0). Other Media records are RCA-not-applicable and are counted apart '
                 'from records with missing RCA information.'),
    ]
    for row, (name, value) in enumerate(info, start=4):
        ws.cell(row=row, column=1, value=name).font = BOLD
        cell = ws.cell(row=row, column=2, value=value)
        cell.alignment = Alignment(wrap_text=True, vertical='top', horizontal='left')
    _widths(ws, [32, 90, 12, 12])

    # Coverage ----------------------------------------------------------------------------------
    ws = book.create_sheet('Coverage')
    _header(ws, 1, ['Project', 'Circle', 'Coverage', 'Accepted records', 'Outage minutes', 'Source files'])
    for row, u in enumerate(units, start=2):
        for col, value in enumerate([u['project'], u['circle'], u['status_label'], u['records'], u['outage_minutes'],
                                     ', '.join(u['source_files'])], start=1):
            ws.cell(row=row, column=col, value=value)
    if not units:
        ws.cell(row=2, column=1, value='No expected projects / circles are configured for this period.')
    _widths(ws, [15, 8, 30, 16, 16, 60])
    ws.freeze_panes = 'A2'

    # Uploads -----------------------------------------------------------------------------------
    ws = book.create_sheet('Uploads')
    _header(ws, 1, ['Upload ID', 'Report name', 'File', 'Uploaded by', 'Uploaded at', 'Status', 'Rows read', 'Imported', 'Updated',
                    'Skipped (unchanged or kept)', 'Rejected', 'Withdrawn', 'Correction'])
    for row, b in enumerate(uploads, start=2):
        c = b.counts or {}
        values = [b.pk, b.report_name, b.original_filename, b.imported_by.get_username() if b.imported_by else None,
                  timezone.localtime(b.uploaded_at).strftime('%d %b %Y %H:%M'), b.get_status_display(), c.get('total'),
                  c.get('inserted'), c.get('updated'), c.get('skipped'), c.get('rejected'), c.get('withdrawn'),
                  'Yes' if c.get('correction') else '']
        for col, value in enumerate(values, start=1):
            ws.cell(row=row, column=col, value=value)
    _widths(ws, [10, 30, 34, 14, 18, 26, 10, 10, 10, 14, 10, 10, 11])
    ws.freeze_panes = 'A2'

    # Summary -----------------------------------------------------------------------------------
    ws = book.create_sheet('Summary')
    k = summary['kpis']
    na = k['rca_not_applicable']
    line = _table(ws, 1, 'Totals', ['Measure', 'Value'], [
        ['Accepted RCA records', k['records']], ['Affected sites', k['affected_sites']],
        ['Recorded outage minutes', k['outage_minutes']], ['Records with outage minutes', k['records_with_minutes']],
        ['RCA-applicable records', k['rca_applicable_records']],
        [f'{MISSING_LABEL} (records)', k['incomplete_records']],
        ['  … Final Bucket blank', k['incomplete_by_field']['final_bucket']], ['  … Bucket - 2 blank', k['incomplete_by_field']['bucket_2']],
        ['  … RCA blank', k['incomplete_by_field']['rca']],
        ['RCA completeness % (applicable records)', k['completeness_pct']],
        [f'{na["label"]} (records)', na['records']], [f'{na["label"]} (outage minutes)', na['outage_minutes']],
    ])
    line = _table(ws, line, 'Project-wise', ['Project', 'Records', 'Outage minutes', 'Affected sites', 'Other Media (RCA not applicable)', MISSING_LABEL],
                  [[p['project'], p['records'], p['outage_minutes'], p['affected_sites'], p['rca_not_applicable'], p['incomplete_records']]
                   for p in summary['projects']])
    line = _table(ws, line, 'Circle-wise', ['Project', 'Circle', 'Records', 'Outage minutes', 'Affected sites', 'Sites in portfolio', 'Records per 100 sites'],
                  [[c['project'], c['circle'], c['records'], c['outage_minutes'], c['affected_sites'], c['portfolio_sites'], c['records_per_100_sites']]
                   for c in sorted(summary['circles'], key=lambda c: (c['project'], c['circle']))])
    line = _table(ws, line, 'Final Bucket (as written; spellings grouped by case and spacing)', ['Final Bucket', 'Records', 'Outage minutes', 'Note'],
                  [[i['label'], i['records'], i['outage_minutes'], 'RCA not applicable' if i['rca_not_applicable'] else 'Unclassified' if i['unclassified'] else '']
                   for i in summary['final_buckets']])
    line = _table(ws, line, 'Bucket - 2 (RCA-applicable records only)', ['Bucket - 2', 'Records', 'Outage minutes', 'Note'],
                  [[i['label'], i['records'], i['outage_minutes'], 'Unclassified' if i['unclassified'] else ''] for i in summary['bucket_2']])
    _table(ws, line, 'Responsibility (current mapping)', ['Responsibility', 'Records', 'Outage minutes'],
           [[responsibility_label(item['bucket']), item['records'], item['outage_minutes']] for item in summary['responsibility']])
    _widths(ws, [52, 14, 16, 16, 30, 34, 20])

    # RCA Master --------------------------------------------------------------------------------
    ws = book.create_sheet('RCA Master')
    _header(ws, 1, SOURCE_HEADER + EXTRA_HEADER)
    mapping = load_bucket_mapping()
    for row, r in enumerate(records, start=2):
        values = [r.reporting_date, r.project_raw, r.circle_raw, r.site_id, r.site_name, r.oa, r.ba, r.om_start_raw, r.outage_minutes,
                  r.final_bucket, r.bucket_2, r.rca_text, applicability(r), get_bucket_classification(r.final_bucket, mapping).mapped_bucket, r.circle,
                  'Imported' if r.source == 'import' else 'Recorded in the portal', r.source_file, r.source_row, r.batch_id, r.pk]
        for col, value in enumerate(values, start=1):
            cell = ws.cell(row=row, column=col, value=None if value == '' else value)
            if col == 1:
                cell.number_format = 'dd-mmm-yyyy'
    _widths(ws, [12, 14, 16, 14, 22, 14, 14, 10, 11, 16, 18, 48, 34, 18, 10, 20, 30, 10, 10, 10])
    ws.freeze_panes = 'A2'
    if records:
        ws.auto_filter.ref = f'A1:{get_column_letter(len(SOURCE_HEADER) + len(EXTRA_HEADER))}{len(records) + 1}'

    out = io.BytesIO()
    book.save(out)
    return out.getvalue()

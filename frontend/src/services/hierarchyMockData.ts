export function getCircle(circleCode: string): HierarchyCircleRow | undefined {
  return MOCK_CIRCLES.find((c) => c.circle.toUpperCase() === circleCode.toUpperCase());
}

export function getOasForCircle(circleCode: string): HierarchyOaRow[] {
  return MOCK_OAS.filter((oa) => oa.circle.toUpperCase() === circleCode.toUpperCase());
}

export function getOa(oaId: string): HierarchyOaRow | undefined {
  return MOCK_OAS.find((oa) => oa.oa_id === oaId);
}

export function getCisForOa(oaId: string): HierarchyCiRow[] {
  return MOCK_CIS.filter((ci) => ci.oa_id === oaId);
}

export function getCi(ciId: string, oaId?: string): HierarchyCiRow | undefined {
  if (oaId) {
    return MOCK_CIS.find((ci) => ci.ci_id === ciId && ci.oa_id === oaId);
  }
  return MOCK_CIS.find((ci) => ci.ci_id === ciId);
}

export function getIesForCi(ciId: string, oaId?: string): HierarchyIeRow[] {
  return MOCK_IES.filter((ie) => ie.ci_id === ciId && (!oaId || ie.oa_id === oaId));
}

export function getIe(ieId: string, ciId?: string): HierarchyIeRow | undefined {
  if (ciId) {
    return MOCK_IES.find((ie) => ie.ie_id === ieId && ie.ci_id === ciId);
  }
  return MOCK_IES.find((ie) => ie.ie_id === ieId);
}

export function getSitesForCi(ciId: string, oaId?: string): HierarchySiteRow[] {
  if (oaId) {
    return MOCK_SITES.filter((s) => s.ci_id === ciId && (!s.oa_id || s.oa_id === oaId));
  }
  return MOCK_SITES.filter((s) => s.ci_id === ciId);
}

export function getSitesForIe(ieId: string, ciId?: string): HierarchySiteRow[] {
  return MOCK_SITES.filter((s) => s.ie_id === ieId && (!ciId || s.ci_id === ciId));
}

export function aggregateKpis(rows: HierarchyKpis[]): HierarchyKpis {
  if (!rows.length) {
    return {
      assigned_sites: 0,
      availability_pct: 0,
      nsla_sites: 0,
      nsla_pct: 0,
      usd: 0,
      incidents: 0,
      l1: null,
      overall_score: null,
      rank: null,
    };
  }

  const totalSites = rows.reduce((acc, r) => acc + r.assigned_sites, 0);
  const totalNslaSites = rows.reduce((acc, r) => acc + r.nsla_sites, 0);
  const totalUsd = rows.reduce((acc, r) => acc + r.usd, 0);
  const totalIncidents = rows.reduce((acc, r) => acc + r.incidents, 0);

  // Weighted pooled availability
  const weightedAvail = totalSites > 0
    ? rows.reduce((acc, r) => acc + r.availability_pct * r.assigned_sites, 0) / totalSites
    : 0;

  return {
    assigned_sites: totalSites,
    availability_pct: Math.round(weightedAvail * 10) / 10,
    nsla_sites: totalNslaSites,
    nsla_pct: totalSites > 0 ? Math.round((totalNslaSites / totalSites) * 1000) / 10 : 0,
    usd: totalUsd,
    incidents: totalIncidents,
    l1: null,
    overall_score: null,
    rank: null,
  };
}
